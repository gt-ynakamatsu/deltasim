"""TB SV file and YAML scenario skeleton generator.

``deltasim gen top.sv --top counter --out-dir ./``

Outputs:
  counter_tb.sv   — SystemVerilog testbench skeleton
  counter_spec.yaml — YAML scenario skeleton
"""

from __future__ import annotations

import os
import textwrap
from typing import Dict, List, Optional

from deltasim.elab.elaborator import ElabDesign


# ---------------------------------------------------------------------------
# TB SV generator
# ---------------------------------------------------------------------------

def generate_tb_sv(design: ElabDesign, out_path: str) -> None:
    """Generate a testbench SV skeleton for *design*."""
    from pathlib import Path
    sv = _build_tb_sv(design)
    p = Path(out_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(sv, encoding="utf-8")


def _build_tb_sv(design: ElabDesign) -> str:
    mod = design.module_name
    tb_name = f"{mod}_tb"
    signals = design.signals
    params = design.params

    lines: List[str] = []
    a = lines.append

    a(f"// Generated by deltasim gen")
    a(f"// Testbench for: {mod}")
    a("`timescale 1ns/1ps")
    a("")
    a(f"module {tb_name};")
    a("")

    # ---------- DUT signals （ポートのみ宣言）----------
    # §18.5: direction が None の内部信号は TB に不要なので含めない
    a("    // ---------- DUT signals ----------")
    for name, info in signals.items():
        if info.direction is None:
            continue  # 内部信号はスキップ
        if info.width == 1:
            a(f"    logic {name};")
        else:
            w = info.width
            a(f"    logic [{w-1}:0] {name};")
    a("")

    # ---------- DUT instance ----------
    # §18.5: ポート（direction あり）のみを接続する（内部信号は除外）
    a("    // ---------- DUT instance ----------")
    if params:
        a(f"    {mod} #(")
        param_items = list(params.items())
        for i, (k, v) in enumerate(param_items):
            comma = "," if i < len(param_items) - 1 else ""
            a(f"        .{k}({v}){comma}")
        a(f"    ) dut (")
    else:
        a(f"    {mod} dut (")

    port_names = [name for name, info in signals.items()
                  if info.direction is not None]
    for i, name in enumerate(port_names):
        comma = "," if i < len(port_names) - 1 else ""
        a(f"        .{name}({name}){comma}")
    a("    );")
    a("")

    # ---------- detect clk / rst ----------
    from deltasim.sim.engine import _detect_clk, _detect_rst
    clk = _detect_clk(signals)
    rst, rst_active_low = _detect_rst(signals)

    # ---------- Clock ----------
    a("    // ---------- Clock (100 MHz = 10ns period) ----------")
    if clk:
        a(f"    initial {clk} = 0;")
        a(f"    always #5 {clk} = ~{clk};")
    else:
        a("    // (no clock detected)")
    a("")

    # ---------- Reset ----------
    a("    // ---------- Reset ----------")
    if rst:
        rst_assert = "0" if rst_active_low else "1"
        rst_release = "1" if rst_active_low else "0"
        a("    initial begin")
        a(f"        {rst} = {rst_assert};")
        if clk:
            a(f"        repeat(10) @(posedge {clk});")
        else:
            a("        #100;")
        a(f"        {rst} = {rst_release};")
        a("    end")
    else:
        a("    // (no reset detected)")
    a("")

    # ---------- Stimulus & Checking ----------
    a("    // ---------- Stimulus & Checking ----------")
    a("    initial begin")
    if clk:
        a("        // Wait for reset to deassert")
        a(f"        repeat(10) @(posedge {clk});")
        a("")
    else:
        a("        #100;")
    a("        // TODO: Add stimuli and assertions here")
    a("        // Example:")

    # Generate commented examples for non-clk, non-rst output/input ports
    for name, info in signals.items():
        if name in (clk, rst):
            continue
        if info.direction == "input":
            a(f"        // {name} = 0;")
        elif info.direction == "output":
            a(f"        // $display(\"{name} = %0d\", {name});")
    a("")
    a("        #100;")
    a("        $finish;")
    a("    end")
    a("")

    # ---------- VCD ----------
    a("    // ---------- VCD ----------")
    a("    initial begin")
    a(f'        $dumpfile("{tb_name}.vcd");')
    a(f"        $dumpvars(0, {tb_name});")
    a("    end")
    a("")
    a(f"endmodule")

    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# YAML scenario skeleton generator
# ---------------------------------------------------------------------------

def generate_yaml_spec(design: ElabDesign, out_path: str) -> None:
    """Generate a YAML scenario skeleton for *design* (§13.2 cases: format)."""
    from deltasim.sim.engine import _detect_clk, _detect_rst
    signals = design.signals
    clk = _detect_clk(signals)
    rst, rst_active_low = _detect_rst(signals)

    lines: List[str] = []
    a = lines.append

    a("# Generated by deltasim gen")
    a(f"# Scenario spec for: {design.module_name}")
    a("version: 1")
    a(f"top: {design.module_name}")
    a("")

    # Clock
    a("clock:")
    if clk:
        a(f"  signal: {clk}")
    else:
        a("  # signal: clk   # no clock detected — set manually")
    a("  period_ns: 10")
    a("")

    # Reset
    a("reset:")
    if rst:
        a(f"  signal: {rst}")
        a(f"  active_low: {'true' if rst_active_low else 'false'}")
    else:
        a("  # signal: rst_n   # no reset detected — set manually")
        a("  # active_low: true")
    a("  duration_cycles: 10")
    a("")

    # Sim (common defaults)
    a("sim:")
    a("  cycles: 30")
    a("  seed: 42")
    a("  # vcd: out.vcd")
    a("")

    # §13.2: cases: list
    a("# §13.2: テストケース一覧")
    a("# cases: が無い旧形式はファイル名を name とする 1 ケースとして扱う（後方互換）")
    a("cases:")
    a(f"  - name: {design.module_name}_basic")
    a("    # seed: 42          # ケース個別のシード（省略でトップレベル sim.seed を使用）")
    a("    # cycles: 30        # ケース個別のサイクル数")
    a("    # skip: false       # true でこのケースをスキップ")
    a("    # skip_reason: ''")

    # Stimulus
    a("    inputs:")
    added = False
    for name, info in signals.items():
        if name in (clk, rst):
            continue
        if info.direction == "input":
            a(f"      # - at: 11")
            a(f"      #   set: {{{name}: 1}}")
            added = True
            break
    if not added:
        a("      []   # inputs なし")

    # Expected
    a("    expected:")
    for name, info in signals.items():
        if info.direction == "output":
            a(f"      # - at: 11")
            a(f"      #   check: {{{name}: 1}}")
            a(f"      # - at: [11, 30]")
            a(f"      #   expr: \"{name} == _cycle - 10\"")
            break
    a("")

    # Reference model
    a("# model:")
    a(f"#   file: {design.module_name}_model.py")
    a(f"#   class: {design.module_name.capitalize()}Model")
    a("#   params: {}")

    # Model
    a("# Reference model (optional):")
    a(f"# model:")
    a(f"#   file: {design.module_name}_model.py")
    a(f"#   class: {design.module_name.capitalize()}Model")
    a("#   params: {}")

    from pathlib import Path
    p = Path(out_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")
